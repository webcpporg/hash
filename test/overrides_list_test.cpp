// detail/overrides.hpp against doc/capabilities.json (spec 4.1): every algorithm of the table has,
// for every backend, its override WEBCPP_HASH_DEFAULT_BACKEND_<ALGORITHM>_<NAME> selected on one
// line (#ifdef for the first backend, #elif defined for the others); every pair of one algorithm's
// overrides its #error; an override of a backend absent from Emscripten its #error there; the
// algorithm's specialisation of override_choice; and no other override, and no other algorithm,
// appears in the file. Written by hand in increment 1, regenerated by tools/hash/measure.py
// --overrides from Task 21: the test holds either way.

#include <webcpp/test/exit_status.hpp>

#include "require.hpp"

#include <boost/core/lightweight_test.hpp>
#include <boost/json.hpp>

#include <cstddef>
#include <cstdlib>
#include <fstream>
#include <functional>
#include <initializer_list>
#include <iostream>
#include <iterator>
#include <set>
#include <sstream>
#include <string>
#include <string_view>
#include <vector>

namespace {

namespace json = boost::json;
using names = std::set<std::string, std::less<>>;

constexpr std::string_view prefix = "WEBCPP_HASH_DEFAULT_BACKEND_";

// The whole file at path; one that cannot be opened ends the test, by name.
std::string read_text(std::string const& path) {
    std::ifstream in(path, std::ios::binary);
    if (!in) {
        std::cerr << "cannot open test data: " << path << '\n';
        std::abort();
    }
    return {std::istreambuf_iterator<char>(in), std::istreambuf_iterator<char>()};
}

std::vector<std::string> lines_of(std::string const& text) {
    std::vector<std::string> lines;
    std::istringstream in(text);
    for (std::string line; std::getline(in, line);) {
        lines.push_back(line);
    }
    return lines;
}

// Every name WEBCPP_HASH_DEFAULT_BACKEND_<X> in the text, <X> of capitals, digits and '_'.
names overrides_in(std::string_view text) {
    names found;
    for (std::size_t at = text.find(prefix); at != std::string_view::npos;
         at = text.find(prefix, at + 1)) {
        std::size_t end = at + prefix.size();
        while (end < text.size() && ((text[end] >= 'A' && text[end] <= 'Z') ||
                                     (text[end] >= '0' && text[end] <= '9') || text[end] == '_')) {
            ++end;
        }
        if (end > at + prefix.size()) {
            found.emplace(text.substr(at, end - at));
        }
    }
    return found;
}

// Every <tag> of "override_choice<kdfs::<tag>>" in the text.
names specialised_in(std::string_view text) {
    names found;
    constexpr std::string_view opening = "override_choice<kdfs::";
    for (std::size_t at = text.find(opening); at != std::string_view::npos;
         at = text.find(opening, at + 1)) {
        std::size_t const start = at + opening.size();
        found.emplace(text.substr(start, text.find('>', start) - start));
    }
    return found;
}

std::size_t count(std::vector<std::string> const& lines, std::string const& line) {
    std::size_t n = 0;
    for (auto const& l : lines) {
        n += l == line ? 1 : 0;
    }
    return n;
}

// Whether `first` is a line of the file and `second` the line after it.
bool has_pair(std::vector<std::string> const& lines, std::string const& first,
              std::string_view second_start) {
    for (std::size_t i = 0; i + 1 < lines.size(); ++i) {
        if (lines[i] == first && lines[i + 1].starts_with(second_start)) {
            return true;
        }
    }
    return false;
}

// A backend of the table: its macro's word and whether Emscripten is among its targets.
struct backend {
    std::string macro;
    bool on_emscripten = false;
};

std::vector<backend> backends_of(json::object const& table) {
    std::vector<backend> backends;
    for (auto const& b : table.at("backends").as_array()) {
        bool emscripten = false;
        for (auto const& target : b.at("targets").as_array()) {
            emscripten = emscripten || target.as_string() == "emscripten";
        }
        backends.push_back(
            {.macro = std::string(b.at("macro").as_string()), .on_emscripten = emscripten});
    }
    return backends;
}

std::string joined(std::initializer_list<std::string_view> parts) {
    std::string text;
    for (std::string_view const part : parts) {
        text.append(part);
    }
    return text;
}

// The lines of one override: its selection, its refusal beside each later backend's override of
// the same algorithm, and its refusal on Emscripten for a backend absent from it.
void check_override(std::vector<std::string> const& lines, std::string const& algorithm,
                    std::vector<backend> const& backends, std::size_t i) {
    std::string const name = joined({prefix, algorithm, "_", backends[i].macro});
    std::size_t const selected = (i == 0 ? count(lines, joined({"#ifdef ", name})) : 0) +
                                 count(lines, joined({"#elif defined(", name, ")"}));
    if (!BOOST_TEST_EQ(selected, 1U)) {
        std::cerr << "  the selection of " << name << '\n';
    }
    for (std::size_t j = i + 1; j < backends.size(); ++j) {
        std::string const other = joined({prefix, algorithm, "_", backends[j].macro});
        std::string const condition = joined({"#if defined(", name, ") && defined(", other, ")"});
        std::string const refusal = joined(
            {"#error \"webcpp::hash: ", name, " and ", other, " are both defined. Keep one.\""});
        if (!BOOST_TEST(has_pair(lines, condition, refusal))) {
            std::cerr << "  the refusal of " << name << " with " << other << '\n';
        }
    }
    if (!backends[i].on_emscripten) {
        std::string const condition =
            joined({"#if defined(WEBCPP_TARGET_EMSCRIPTEN) && defined(", name, ")"});
        if (!BOOST_TEST(has_pair(lines, condition,
                                 joined({"#error \"webcpp::hash: ", name, " selects "})))) {
            std::cerr << "  the refusal of " << name << " on Emscripten\n";
        }
    }
}

}  // namespace

int main() {
    std::string const doc = WEBCPP_TEST_HASH_DOC;
    std::string const include = WEBCPP_TEST_HASH_INCLUDE;
    json::value const parsed = json::parse(read_text(doc + "/capabilities.json"));
    webcpp::test::require(parsed.is_object());
    json::object const& table = parsed.as_object();
    std::string const file = read_text(include + "/webcpp/hash/detail/overrides.hpp");
    std::vector<std::string> const lines = lines_of(file);
    std::vector<backend> const backends = backends_of(table);

    names expected;
    names algorithms;
    for (auto const& a : table.at("algorithms").as_array()) {
        std::string const algorithm(a.at("macro").as_string());
        algorithms.emplace(a.at("name").as_string());
        for (std::size_t i = 0; i < backends.size(); ++i) {
            expected.insert(joined({prefix, algorithm, "_", backends[i].macro}));
            check_override(lines, algorithm, backends, i);
        }
    }

    names const found = overrides_in(file);
    for (auto const& name : found) {
        if (!BOOST_TEST(expected.contains(name))) {
            std::cerr << "  an override of no cell of capabilities.json: " << name << '\n';
        }
    }
    BOOST_TEST_EQ(found.size(), expected.size());
    BOOST_TEST((specialised_in(file) == algorithms));
    return webcpp::test::exit_status(boost::report_errors());
}
