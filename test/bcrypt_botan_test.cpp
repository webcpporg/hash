// bcrypt on backends::botan (Botan 3.14.1's generate_bcrypt and check_bcrypt):
// - every case of Botan's passhash/bcrypt.vec whose comment names a source other than Botan
//   (jBCrypt 0.3, openwall's john-dev list, bcrypt-tester and crypt_blowfish, OpenBSD's bcrypt
//   code), read at run time: its salt and cost parsed from the string and recomputed through
//   bcrypt, and checked through bcrypt_verify, a wrong password false; a password of more than 72
//   bytes refused by both, its first 72 bytes giving the string (bcrypt reads no more);
// - the salt given is the one written in the string, and the version the one asked;
// - the guards, each refusal leaving the output as it was: an output of 59 and 61, a salt of 15
//   and 17, a password of 73 bytes and one with a zero byte, a cost of 3 and 32, a version 'c',
//   strings not of bcrypt's form, and Botan's limit, a cost of 19, unsupported_by_backend;
// - no default (design D34), and backends::botan's cell.

