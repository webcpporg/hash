// The In and Out cases of a Botan .vec file's section `[header]`, from the line after `from` (the
// section's start when empty) to the line `until` (the section's end when empty).
std::vector<kat_entry> vec_cases(std::string const& file, std::string_view header,
                                 std::string_view from, std::string_view until) {
    std::vector<kat_entry> entries;
    bool in_section = false;
    bool started = from.empty();
    bytes input;
    for (auto const& line : test::read_lines(std::string(WEBCPP_TEST_BOTAN_VECTORS) + "/" + file)) {
        if (line.starts_with('[')) {
            in_section = line == "[" + std::string(header) + "]";
            continue;
        }
        if (!in_section) {
            continue;
        }
        if (!from.empty() && line == from) {
            started = true;
            continue;
        }
        if (!until.empty() && line == until) {
            break;
        }
        if (!started) {
            continue;
        }
        if (line.starts_with("In =")) {
            input = test::from_hex(line.size() > 5 ? line.substr(5) : std::string{});
        } else if (line.starts_with("Out = ")) {
            entries.push_back({.message = input, .expected = test::from_hex(line.substr(6))});
        }
    }
    return entries;
}

// Whirlpool: the test vectors of its authors (Barreto and Rijmen, "The WHIRLPOOL Hashing
