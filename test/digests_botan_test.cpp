// The stanzas of an OpenSSL test file: "Name = value" lines up to a blank line.
std::vector<std::map<std::string, std::string>> stanzas_of(std::string const& path) {
    std::vector<std::map<std::string, std::string>> stanzas(1);
    for (auto const& line : test::read_lines(path)) {
        if (line.empty()) {
            stanzas.emplace_back();
            continue;
        }
        auto const separator = line.find(" = ");
        if (line.front() == '#' || separator == std::string::npos) {
            continue;
        }
        stanzas.back()[line.substr(0, separator)] = line.substr(separator + 3);
    }
    return stanzas;
}

// The bytes of an EVP value: hex, or a quoted string's characters.
bytes value_bytes(std::string const& value) {
    if (value.size() >= 2 && value.front() == '"' && value.back() == '"') {
        return {value.begin() + 1, value.end() - 1};
    }
    return test::from_hex(value);
}

// SHAKE: the SHAKE cases of evpmd_sha.txt (FIPS 202's examples, 12 at OpenSSL 3.5.9's pin, 6 of
// them past one rate block); Boost.Hash2's stream at random sizes from 1 to 700 bytes and at
// 10,000.
template <class Tag, class Shake>
void check_shake(std::string_view openssl_name, std::size_t rate, std::size_t& run,
                 std::size_t& past_a_block) {
    test::random_source rnd(test::agreement_seed);
    for (auto const& entry : stanzas_of(WEBCPP_TEST_OPENSSL_EVP_DATA "/evpmd_sha.txt")) {
        auto const digest = entry.find("Digest");
        if (digest == entry.end() || digest->second != openssl_name) {
            continue;
        }
        auto const input = value_bytes(entry.at("Input"));
        bytes message;
        auto const count = entry.contains("Count") ? std::stoul(entry.at("Count")) : 1UL;
        for (unsigned long index = 0; index < count; ++index) {
            message.insert(message.end(), input.begin(), input.end());
        }
        auto const expected = test::from_hex(entry.at("Output"));
        if (!BOOST_TEST(both_give<Tag>(rnd, message, expected))) {
            std::cerr << "  " << openssl_name << " of evpmd_sha.txt, " << expected.size()
                      << " bytes\n";
        }
        past_a_block += expected.size() > rate ? 1U : 0U;
        ++run;
    }
    for (std::size_t index = 0; index < 200; ++index) {
        auto const input = next_input(rnd, index);
        std::size_t const size = index == 199 ? 10000 : rnd.between(1, 700);
        if (!BOOST_TEST(both_give<Tag>(rnd, input, hash2_of<Shake>(input, size)))) {
            std::cerr << "  " << openssl_name << ", case " << index << ", " << size << " bytes\n";
            return;
        }
    }
}

// The value after "<name>:\t" on a line of blake2b-kat.txt.
std::string kat_value(std::string const& line, std::string_view name) {
    std::string const prefix = std::string(name) + ":\t";
    test::require(BOOST_TEST(line.starts_with(prefix)));
    return line.substr(prefix.size());
}

// BLAKE2b's keyed vectors, blake2b-kat.txt (a 64-byte key, inputs of 0 to 255 bytes).
void check_blake2_keyed_kat(test::random_source& rnd) {
    std::size_t keyed = 0;
    auto const lines = test::read_lines(WEBCPP_TEST_BLAKE2_VECTORS "/blake2b-kat.txt");
    for (std::size_t index = 0; index + 2 < lines.size(); ++index) {
        if (!lines[index].starts_with("in:")) {
            continue;
        }
        auto const input = test::from_hex(kat_value(lines[index], "in"));
        auto const key = test::from_hex(kat_value(lines[index + 1], "key"));
        auto const expected = test::from_hex(kat_value(lines[index + 2], "hash"));
        if (!BOOST_TEST(both_give<digests::blake2b>(rnd, input, expected, {.key = key}))) {
            std::cerr << "  blake2b-kat.txt, input of " << input.size() << " bytes\n";
        }
        index += 2;
        ++keyed;
    }
    BOOST_TEST_EQ(keyed, 256U);
}

// The unkeyed BLAKE2b and BLAKE2s cases of blake2-kat.json.
void check_blake2_unkeyed_kat(test::random_source& rnd) {
    std::size_t unkeyed_b = 0;
    std::size_t unkeyed_s = 0;
    boost::system::error_code ec;
    auto const doc =
        json::parse(test::read_text(WEBCPP_TEST_BLAKE2_VECTORS "/blake2-kat.json"), ec);
    test::require(BOOST_TEST(!ec));
    for (auto const& entry : doc.as_array()) {
        auto const& vector = entry.as_object();
        auto const& key = vector.at("key").as_string();
        if (!key.empty()) {
            continue;
        }
        auto const input = test::from_hex(vector.at("in").as_string());
        auto const expected = test::from_hex(vector.at("out").as_string());
        auto const& name = vector.at("hash").as_string();
        bool agreed = true;
        if (name == "blake2b") {
            agreed = both_give<digests::blake2b>(rnd, input, expected);
            ++unkeyed_b;
        } else if (name == "blake2s") {
            agreed = both_give<digests::blake2s_256>(rnd, input, expected);
            ++unkeyed_s;
        }
        if (!BOOST_TEST(agreed)) {
            std::cerr << "  blake2-kat.json, " << name << ", input of " << input.size()
                      << " bytes\n";
        }
    }
    BOOST_TEST_EQ(unkeyed_b, 256U);
    BOOST_TEST_EQ(unkeyed_s, 256U);
}

// BLAKE2b at every size from 1 to 64 bytes, unkeyed and keyed with 1 to 64 bytes, against
// libsodium.
void check_blake2b_sizes(test::random_source& rnd) {
    for (std::size_t index = 0; index < 256; ++index) {
        auto const input = next_input(rnd, index);
        std::size_t const size = (index % 64) + 1;
        auto const key = index < 128 ? bytes{} : rnd.bytes((index % 64) + 1);
        hash::digest_options<digests::blake2b> const options{.key = key, .output_size = size};
        bytes expected(size);
        test::require(BOOST_TEST(
            (hash::digest_of<digests::blake2b, hash::backends::sodium>(expected, input, options)
                 .has_value())));
        if (!BOOST_TEST(both_give<digests::blake2b>(rnd, input, expected, options))) {
            std::cerr << "  blake2b against libsodium, " << size << " bytes, key " << key.size()
                      << '\n';
            return;
        }
    }
}

// The options Botan's BLAKE2b does not take: unsupported_by_backend, the output untouched.
void check_blake2b_refused() {
    std::array<std::uint8_t, 16> const sixteen{1, 2, 3};
    std::array<hash::digest_options<digests::blake2b>, 2> const refused_options{
        {
            {.salt = sixteen},
            {.personalisation = sixteen},
        },
    };
    for (auto const& options : refused_options) {
        std::array<std::uint8_t, 64> output{};
        output.fill(0x55);
        auto const refused = hash::digest_of<digests::blake2b, botan>(output, {}, options);
        BOOST_TEST(refused.has_error() && refused.error() == hash::error::unsupported_by_backend);
        BOOST_TEST(std::ranges::all_of(output, [](std::uint8_t b) { return b == 0x55; }));
        auto const made = hash::hasher<digests::blake2b, botan>::make(options);
        BOOST_TEST(made.has_error() && made.error() == hash::error::unsupported_by_backend);
    }
}

// BLAKE2b and BLAKE2s against BLAKE2's vectors and libsodium, and the options Botan refuses.
void check_blake2() {
    test::random_source rnd(test::agreement_seed);
    check_blake2_keyed_kat(rnd);
    check_blake2_unkeyed_kat(rnd);
    check_blake2b_sizes(rnd);
    check_blake2b_refused();
}

