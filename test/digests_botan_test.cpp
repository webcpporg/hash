// One whole-byte entry of a KAT file: the message and the expected output.
struct kat_entry {
    bytes message;
    bytes expected;
};

// The entries of XKCP's ShortMsgKAT file whose Len is a multiple of 8.
std::vector<kat_entry> read_kat(std::string const& file) {
    std::vector<kat_entry> entries;
    std::size_t bits = 0;
    bytes message;
    for (auto const& line : test::read_lines(std::string(WEBCPP_TEST_XKCP_VECTORS) + "/" + file)) {
        if (line.starts_with("Len = ")) {
            bits = std::stoul(line.substr(6));
        } else if (line.starts_with("Msg = ")) {
            message = test::from_hex(line.substr(6));
            message.resize(bits / 8);
        } else if (line.starts_with("MD = ") && bits % 8 == 0) {
            entries.push_back({.message = message, .expected = test::from_hex(line.substr(5))});
        }
    }
    return entries;
}

// Every whole-byte entry of XKCP's SHA-3 KAT file through `Tag` on Botan; the file holds 256.
template <class Tag>
void check_sha3_kat(std::string const& file) {
    test::random_source rnd(test::agreement_seed);
    auto const entries = read_kat(file);
    BOOST_TEST_EQ(entries.size(), std::size_t{256});
    for (auto const& entry : entries) {
        if (!BOOST_TEST(both_give<Tag>(rnd, entry.message, entry.expected))) {
            std::cerr << "  " << file << ", Len = " << entry.message.size() * 8 << '\n';
        }
    }
}

