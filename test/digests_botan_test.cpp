// The digests of backends::botan (spec 2.15, design D44): Botan 3.14.1's HashFunction and XOF,
// each tag through digest_of and through a hasher fed in random pieces (empty ones included):
// - MD5, SHA-1, the five SHA-2 Botan has, the four SHA-3, RIPEMD-160 and BLAKE2s-256 against
//   Boost.Hash2 on seeded random inputs, and FIPS 180-4's "abc" for SHA-1 and the SHA-2;
// - SHA3-n against XKCP's ShortMsgKAT_SHA3-n.txt (its whole-byte entries); Keccak-224 to
//   Keccak-512 against the Keccak team's digests of "", 0xCC and "abc" (Task 5's values) and
//   Boost.Hash2's Keccak (keccak_base with the padding byte 0x01);
// - SHAKE128 and SHAKE256 against the SHAKE cases of OpenSSL's evpmd_sha.txt (FIPS 202's
//   examples, past one rate block) and Boost.Hash2's stream at random sizes;
// - BLAKE2b of 1 to 64 bytes, unkeyed and keyed, against BLAKE2's blake2-kat.json (unkeyed) and
//   blake2b-kat.txt (keyed) and libsodium at every size; BLAKE2s-256 against blake2-kat.json; a
//   salt or a personalisation unsupported_by_backend, the output untouched;
// - SM3 against GB/T 32905-2016's two examples; Streebog-256 and -512 against RFC 6986 section
//   10's two messages; Whirlpool against the ISO/IEC 10118-3 vectors of its authors and the cases
//   of Botan's hash/whirlpool.vec generated by OpenSSL; Skein-512-512 against the Skein 1.3
//   paper's Appendix C and the [Skein-512(512)] cases of Botan's hash/skein.vec;
