// The bytes from `first` down by one for `count` bytes: the Skein paper's messages.
bytes counting_down(std::uint8_t first, std::size_t count) {
    bytes out(count);
    for (std::size_t index = 0; index < count; ++index) {
        out[index] = static_cast<std::uint8_t>(first - index);
    }
    return out;
}

// Skein-512-512: the Skein 1.3 paper's Appendix C examples (Ferguson et al., "The Skein Hash
// Function Family", version 1.3, 2010, C.3: one byte 0xFF, 64 bytes and 128 bytes counting down
