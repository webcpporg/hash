// The family's guard on a fixed size, before Botan: the output untouched.
void check_guards() {
    std::array<std::uint8_t, 31> short_output{};
    short_output.fill(0x55);
    auto const refused = hash::digest_of<digests::sha2_256, botan>(short_output, {});
    BOOST_TEST(refused.has_error() && refused.error() == hash::error::invalid_output_size);
    BOOST_TEST(std::ranges::all_of(short_output, [](std::uint8_t b) { return b == 0x55; }));
}

// backends::botan has each of these tags, and is the default of none (design D34).
template <class... Tag>
constexpr bool in_botan_by_name() {
    return ((hash::backend_has_v<botan, Tag, void> &&
             !std::is_same_v<hash::default_backend<Tag>, botan>) &&
            ...);
}

static_assert(
    in_botan_by_name<digests::md5, digests::sha1, digests::sha2_224, digests::sha2_256,
                     digests::sha2_384, digests::sha2_512, digests::sha2_512_256, digests::sha3_224,
                     digests::sha3_256, digests::sha3_384, digests::sha3_512, digests::shake_128,
                     digests::shake_256, digests::keccak_224, digests::keccak_256,
                     digests::keccak_384, digests::keccak_512, digests::blake2b,
                     digests::blake2s_256, digests::ripemd_160, digests::sm3, digests::streebog_256,
                     digests::streebog_512, digests::whirlpool, digests::skein_512>());
// Botan 3.14.1 has no SHA-512/224 and no public cSHAKE (design D44).
static_assert(!hash::backend_has_v<botan, digests::sha2_512_224, void>);
static_assert(!hash::backend_has_v<botan, digests::cshake_128, void>);
// Streebog, Whirlpool and Skein-512 are Botan's alone: the call names it.
static_assert(std::is_same_v<hash::default_backend<digests::whirlpool>, hash::detail::no_default>);
static_assert(std::is_same_v<hash::default_backend<digests::skein_512>, hash::detail::no_default>);

