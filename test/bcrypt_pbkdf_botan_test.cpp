#include <type_traits>
#include <vector>

namespace {

namespace hash = webcpp::hash;
namespace kdfs = webcpp::hash::kdfs;
namespace test = webcpp::test;
using hash::backends::botan;
using bytes = std::vector<std::uint8_t>;

constexpr std::uint8_t untouched = 0x5A;

bool failed_with(boost::system::result<void> const& outcome, hash::error expected) {
    return outcome.has_error() && outcome.error() == expected;
}

bool all_of(std::span<std::uint8_t const> data, std::uint8_t value) {
    return std::ranges::all_of(data, [value](std::uint8_t byte) { return byte == value; });
}

// The source each comment of bcrypt_pbkdf.vec names.
std::string_view source_of(std::string_view comment) {
    static std::map<std::string_view, std::string_view> const sources{
        {
            "# From https://github.com/dchest/bcrypt_pbkdf/blob/master/bcrypt_pbkdf_test.go",
            "dchest's test",
        },
        {"# Generated by OpenBSD bcrypt_pbkdf", "OpenBSD"},
        {"# Generated by https://github.com/dchest/bcrypt_pbkdf/", "dchest's package"},
    };
    auto const found = sources.find(comment);
    test::require(BOOST_TEST(found != sources.end()));
    return found->second;
}

// One case: the passphrase is text, the salt and the output hex.
struct pbkdf_case {
    std::string passphrase;
    bytes salt;
    std::uint32_t rounds = 0;
};

void check_case(pbkdf_case const& c, std::string_view expected, std::string_view source,
                std::size_t index) {
    bytes output(expected.size() / 2, untouched);
    std::span<std::uint8_t const> const password(
        // NOLINTNEXTLINE(cppcoreguidelines-pro-type-reinterpret-cast): the text's bytes
        reinterpret_cast<std::uint8_t const*>(c.passphrase.data()), c.passphrase.size());
    auto const done = hash::bcrypt_pbkdf<botan>(output, password, c.salt, c.rounds);
    if (!BOOST_TEST(done.has_value()) ||
        !BOOST_TEST_EQ(test::to_hex(output), std::string(expected))) {
        std::cerr << "  bcrypt_pbkdf.vec, " << source << " case " << index << ": rounds "
                  << c.rounds << ", output " << output.size() << '\n';
    }
}

void check_vectors() {
    std::map<std::string_view, std::size_t> counts;
    std::string_view source;
    pbkdf_case c;
    for (auto const& line :
         test::read_lines(std::string(WEBCPP_TEST_BOTAN_VECTORS) + "/bcrypt_pbkdf.vec")) {
        std::string_view const text(line);
        if (text.starts_with('#')) {
            source = source_of(text);
        } else if (text.starts_with("Passphrase = ")) {
            c.passphrase = std::string(text.substr(13));
        } else if (text.starts_with("Salt = ")) {
            c.salt = test::from_hex(text.substr(7));
        } else if (text.starts_with("Iterations = ")) {
            c.rounds = static_cast<std::uint32_t>(std::stoul(std::string(text.substr(13))));
        } else if (text.starts_with("Output = ")) {
            test::require(BOOST_TEST(!source.empty()));
            std::string expected(text.substr(9));
            std::ranges::transform(expected, expected.begin(), [](char x) {
                return static_cast<char>(x >= 'A' && x <= 'F' ? x - 'A' + 'a' : x);
            });
            check_case(c, expected, source, counts[source]);
            ++counts[source];
        }
    }
    BOOST_TEST_EQ(counts["dchest's test"], 1U);
    BOOST_TEST_EQ(counts["OpenBSD"], 2U);
    BOOST_TEST_EQ(counts["dchest's package"], 33U);
}

// OpenBSD's bcrypt_pbkdf.c: rounds < 1, an empty password, salt or key, a key of more than
// sizeof(out) * sizeof(out) = 1,024 bytes and a salt of more than 1 << 20 bytes are refused.
void check_guards() {
    bytes const password{'p', 'w'};
    bytes const salt{1, 2, 3, 4};
    bytes output(32, untouched);
    bytes longer(1025, untouched);
    BOOST_TEST(failed_with(hash::bcrypt_pbkdf<botan>(std::span<std::uint8_t>{}, password, salt, 1),
                           hash::error::invalid_output_size));
    BOOST_TEST(failed_with(hash::bcrypt_pbkdf<botan>(longer, password, salt, 1),
                           hash::error::invalid_output_size));
    BOOST_TEST(all_of(longer, untouched));
    BOOST_TEST(failed_with(hash::bcrypt_pbkdf<botan>(output, password, {}, 1),
                           hash::error::invalid_salt_size));
    bytes const salt_too_long(1048577, 9);
    BOOST_TEST(failed_with(hash::bcrypt_pbkdf<botan>(output, password, salt_too_long, 1),
                           hash::error::invalid_salt_size));
    BOOST_TEST(
        failed_with(hash::bcrypt_pbkdf<botan>(output, {}, salt, 1), hash::error::invalid_key_size));
    BOOST_TEST(failed_with(hash::bcrypt_pbkdf<botan>(output, password, salt, 0),
                           hash::error::invalid_iterations));
    BOOST_TEST(all_of(output, untouched));
    // The limits themselves are computed.
    longer.resize(1024);
    BOOST_TEST((hash::bcrypt_pbkdf<botan>(longer, password, salt, 1).has_value()));
    BOOST_TEST(!all_of(longer, untouched));
    bytes const longest_salt(1048576, 9);
    BOOST_TEST((hash::bcrypt_pbkdf<botan>(output, password, longest_salt, 1).has_value()));
    BOOST_TEST(!all_of(output, untouched));
}

static_assert(hash::backend_has_v<botan, kdfs::bcrypt_pbkdf, void>);
static_assert(std::is_same_v<hash::default_backend<kdfs::bcrypt_pbkdf>, hash::detail::no_default>);

}  // namespace

int main() {
    check_vectors();
    check_guards();
    return webcpp::test::exit_status(boost::report_errors());
}
