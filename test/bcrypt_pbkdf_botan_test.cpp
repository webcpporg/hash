// OpenBSD's bcrypt_pbkdf on backends::botan (Botan 3.14.1's "Bcrypt-PBKDF"):
// - every case of Botan's bcrypt_pbkdf.vec, read at run time, each from a source its comments name
//   (dchest's Go package and its test, OpenBSD's bcrypt_pbkdf): computed, its count asserted;
// - the guards at OpenBSD's limits (bcrypt_pbkdf.c), each refusal leaving the output as it was: an
//   output of 0 and 1,025 bytes, a salt of 0 and 1,048,577, an empty password, no round; and the
//   limits themselves computed, an output of 1,024 bytes and a salt of 1,048,576;
// - no default (design D34), and backends::botan's cell.

#include <webcpp/hash/bcrypt.hpp>
#include <webcpp/hash/error.hpp>
#include <webcpp/hash/kdf.hpp>
#include <webcpp/test/exit_status.hpp>

#include "require.hpp"
#include "support/data_file.hpp"
#include "support/hex.hpp"

#include <boost/core/lightweight_test.hpp>
#include <boost/system/result.hpp>

#include <algorithm>
#include <cstddef>
#include <cstdint>
#include <iostream>
#include <map>
#include <span>
#include <string>
